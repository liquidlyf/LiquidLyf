"""Builds the launcher and monochrome vector drawables from branding/logo-mark*.svg, and the splash
(the still picture at the start) from branding/logo-full*.svg.

Usage, from the repo root:  python app/scripts/generate_launcher_icons.py .
Re-run it after the logo SVGs change. Needs only the Python standard library.
"""
import math, re, sys, pathlib

root = pathlib.Path(sys.argv[1])
res = root / "app/src/main/res"

def paths(svg):
    t = (root / "branding" / svg).read_text(encoding="utf-8")
    return [(m.group(1), m.group(3), bool(m.group(2))) for m in
            re.finditer(r'<path fill="(#[0-9A-Fa-f]{6})"( fill-rule="evenodd")? d="([^"]+)"', t)]

def tokens(d):
    return re.findall(r'[MLAZHVQmlazhvq]|-?\d*\.?\d+(?:e-?\d+)?', d)

def arc_points(x1, y1, rx, ry, phi, fa, fs, x2, y2, n=64):
    # W3C SVG arc implementation notes, F.6.5
    p = math.radians(phi); c, s = math.cos(p), math.sin(p)
    dx, dy = (x1 - x2) / 2, (y1 - y2) / 2
    x1p, y1p = c * dx + s * dy, -s * dx + c * dy
    lam = x1p**2 / rx**2 + y1p**2 / ry**2
    if lam > 1: rx, ry = rx * math.sqrt(lam), ry * math.sqrt(lam)
    num = rx*rx*ry*ry - rx*rx*y1p*y1p - ry*ry*x1p*x1p
    den = rx*rx*y1p*y1p + ry*ry*x1p*x1p
    co = math.sqrt(max(0, num / den)) * (-1 if fa == fs else 1)
    cxp, cyp = co * rx * y1p / ry, -co * ry * x1p / rx
    cx, cy = c * cxp - s * cyp + (x1 + x2) / 2, s * cxp + c * cyp + (y1 + y2) / 2
    ang = lambda ux, uy, vx, vy: math.atan2(ux*vy - uy*vx, ux*vx + uy*vy)
    t1 = ang(1, 0, (x1p - cxp) / rx, (y1p - cyp) / ry)
    dt = ang((x1p - cxp) / rx, (y1p - cyp) / ry, (-x1p - cxp) / rx, (-y1p - cyp) / ry)
    if not fs and dt > 0: dt -= 2 * math.pi
    if fs and dt < 0: dt += 2 * math.pi
    out = []
    for i in range(n + 1):
        t = t1 + dt * i / n
        out.append((cx + rx * math.cos(t) * c - ry * math.sin(t) * s, cy + rx * math.cos(t) * s + ry * math.sin(t) * c))
    return out

def outline(d):
    tk, i, pts, cur, cmd = tokens(d), 0, [], (0, 0), None
    num = lambda: float(tk[i])
    while i < len(tk):
        if re.match(r'[A-Za-z]', tk[i]): cmd = tk[i]; i += 1
        if cmd in 'Zz': continue
        if cmd in 'ML':
            cur = (float(tk[i]), float(tk[i+1])); i += 2; pts.append(cur)
        elif cmd == 'A':
            a = [float(v) for v in tk[i:i+7]]; i += 7
            pts += arc_points(cur[0], cur[1], a[0], a[1], a[2], int(a[3]), int(a[4]), a[5], a[6]); cur = (a[5], a[6])
        elif cmd == 'H':  # the letters of logo-full.svg
            cur = (float(tk[i]), cur[1]); i += 1; pts.append(cur)
        elif cmd == 'V':
            cur = (cur[0], float(tk[i])); i += 1; pts.append(cur)
        elif cmd == 'Q':
            qx, qy, x2, y2 = (float(v) for v in tk[i:i+4]); i += 4
            pts += [((1-t)**2 * cur[0] + 2*(1-t)*t * qx + t*t * x2, (1-t)**2 * cur[1] + 2*(1-t)*t * qy + t*t * y2)
                    for t in (k / 16 for k in range(1, 17))]
            cur = (x2, y2)
        else:
            raise SystemExit(f"unsupported command {cmd}")
    return pts

mark, mono = paths("logo-mark.svg"), paths("logo-mark-mono.svg")
pts = [p for _, d, _ in mark for p in outline(d)]
xs, ys = [p[0] for p in pts], [p[1] for p in pts]
cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
rmax = max(math.hypot(x - cx, y - cy) for x, y in pts)
print(f"mark bbox x {min(xs):.1f}-{max(xs):.1f}  y {min(ys):.1f}-{max(ys):.1f}  centre ({cx:.1f},{cy:.1f})  max radius {rmax:.1f}")

# Optical centring (maintainer, 15 Nov 2026): a heart is top-heavy (area centroid y 220.5 vs the
# box centre 256), so the box-centred mark looked high. Move it down by half that gap, in mark
# units of the 512 viewBox; positive is down. Horizontal is already centred.
OPTICAL_DY = 18

def vector(size_dp, viewport, radius, shapes, fill_override=None, comment=""):
    """shapes drawn in a group scaled so the mark's farthest point sits at `radius` from the centre."""
    s = radius / rmax
    tx, ty = viewport / 2 - cx * s, viewport / 2 - (cy - OPTICAL_DY) * s
    body = "".join(
        f'        <path\n            android:fillColor="{fill_override or fill}"\n'
        + ('            android:fillType="evenOdd"\n' if evenodd else '')
        + f'            android:pathData="{d}" />\n'
        for fill, d, evenodd in shapes)
    return (f'<?xml version="1.0" encoding="utf-8"?>\n{comment}'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size_dp}dp"\n    android:height="{size_dp}dp"\n'
            f'    android:viewportWidth="{viewport}"\n    android:viewportHeight="{viewport}">\n'
            f'    <group\n        android:scaleX="{s:.5f}"\n        android:scaleY="{s:.5f}"\n'
            f'        android:translateX="{tx:.4f}"\n        android:translateY="{ty:.4f}">\n'
            f'{body}    </group>\n</vector>\n')

note = "<!-- Generated by app/scripts/generate_launcher_icons.py from branding/logo-mark*.svg. Don't edit by hand. -->\n"
# Adaptive foreground: 108dp canvas, safe zone is a 66dp circle (radius 33). Keep the mark within radius 30.
R_FG = 30
# After the optical shift, the farthest point must still sit inside the safe zone.
shifted = max(math.hypot(x - cx, y - cy + OPTICAL_DY) for x, y in pts) * R_FG / rmax
tip = (max(ys) - cy + OPTICAL_DY) * R_FG / rmax
print(f"optical shift {OPTICAL_DY} units = {OPTICAL_DY * R_FG / rmax:.2f} dp; farthest point {shifted:.2f} dp from the centre (tip {tip:.2f} dp); safe radius 33")
assert shifted <= 33, "the shifted mark leaves the adaptive icon's safe zone"
out = {
    # The app icon (the maintainer's choice on 15 Nov 2026, replacing A1's white-on-red): the
    # full-colour mark on a white background.
    "drawable/ic_launcher_foreground.xml": vector(108, 108, R_FG, mark, comment=note),
    "drawable/ic_launcher_monochrome.xml": vector(108, 108, R_FG, mono, "#000000", note),         # Android 13+ themed icon
}
for name, xml in out.items():
    (res / name).write_text(xml, encoding="utf-8", newline="\n")
    print("wrote", name)


# The still picture at the start (D25, 20 Nov 2026): the stacked logo, light and dark (drawable-night
# follows the phone's dark mode, which is what the system uses for it). Android shows it 288 dp square,
# masked to a 192 dp circle; the art is 161 dp wide, centred, so it fits that circle. StartLogo.kt draws
# the same art at the same size and place when the app takes over (SPLASH_ART_DP, ART_BOX): keep both in step.
SPLASH_DP, SPLASH_ART_DP = 288, 161

def stacked_splash(svg):
    shapes = paths(svg)
    p = [q for _, d, _ in shapes for q in outline(d)]
    x0, x1 = min(q[0] for q in p), max(q[0] for q in p)
    y0, y1 = min(q[1] for q in p), max(q[1] for q in p)
    s = SPLASH_ART_DP / SPLASH_DP * 108 / (x1 - x0)
    tx, ty = 54 - (x0 + x1) / 2 * s, 54 - (y0 + y1) / 2 * s
    corner = max(math.hypot((x - (x0 + x1) / 2) * s, (y - (y0 + y1) / 2) * s) for x, y in p) * SPLASH_DP / 108
    print(f"{svg}: art box x {x0:.2f}-{x1:.2f}  y {y0:.2f}-{y1:.2f}; farthest point {corner:.1f} dp from the centre (circle 96)")
    assert corner <= 96, "the stacked logo leaves the splash circle"
    body = "".join(f'        <path\n            android:fillColor="{fill}"\n            android:pathData="{d}" />\n' for fill, d, _ in shapes)
    return (f'<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Generated by app/scripts/generate_launcher_icons.py from branding/{svg}. Don\'t edit by hand. -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="108dp"\n    android:height="108dp"\n'
            f'    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            f'    <group\n        android:scaleX="{s:.6f}"\n        android:scaleY="{s:.6f}"\n'
            f'        android:translateX="{tx:.4f}"\n        android:translateY="{ty:.4f}">\n'
            f'{body}    </group>\n</vector>\n')

for name, svg in {"drawable/ic_splash_logo.xml": "logo-full.svg", "drawable-night/ic_splash_logo.xml": "logo-full-dark.svg"}.items():
    (res / name).parent.mkdir(parents=True, exist_ok=True)
    (res / name).write_text(stacked_splash(svg), encoding="utf-8", newline="\n")
    print("wrote", name)


# Legacy icons (Android 7.x, no adaptive icons): a circle of the background colour with the mark.
def legacy(bg, shapes, fill_override=None):
    s = R_FG / rmax
    tx, ty = 54 - cx * s, 54 - (cy - OPTICAL_DY) * s
    body = "".join(
        f'        <path\n            android:fillColor="{fill_override or fill}"\n'
        + ('            android:fillType="evenOdd"\n' if evenodd else '')
        + f'            android:pathData="{d}" />\n' for fill, d, evenodd in shapes)
    return (f'<?xml version="1.0" encoding="utf-8"?>\n{note}<!-- Launcher icon for Android 7.x (API 24-25), which has no adaptive icons. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="48dp"\n    android:height="48dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            f'    <path\n        android:fillColor="{bg}"\n        android:pathData="M54,4.5a49.5,49.5 0,1 1,0 99a49.5,49.5 0,1 1,0 -99z" />\n'
            f'    <group\n        android:scaleX="{s:.5f}"\n        android:scaleY="{s:.5f}"\n'
            f'        android:translateX="{tx:.4f}"\n        android:translateY="{ty:.4f}">\n'
            f'{body}    </group>\n</vector>\n')

def adaptive(bg_color_res, fg):
    return ('<?xml version="1.0" encoding="utf-8"?>\n' + note +
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            f'    <background android:drawable="@color/{bg_color_res}" />\n'
            f'    <foreground android:drawable="@drawable/{fg}" />\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
            '</adaptive-icon>\n')

more = {
    # White background, full-colour mark (15 Nov 2026).
    res / "mipmap-anydpi-v26/ic_launcher.xml": adaptive("ic_launcher_white", "ic_launcher_foreground"),
    res / "mipmap-anydpi-v26/ic_launcher_round.xml": adaptive("ic_launcher_white", "ic_launcher_foreground"),
    res / "mipmap-anydpi/ic_launcher.xml": legacy("#FFFFFF", mark),
    res / "mipmap-anydpi/ic_launcher_round.xml": legacy("#FFFFFF", mark),
}
for path, xml in more.items():
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(xml, encoding="utf-8", newline="\n")
    print("wrote", path.relative_to(root))
