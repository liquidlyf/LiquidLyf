// Bundles the Worker's pure escalation logic into backend/apps-script/Shared.js (global
// `LiquidLyf`) for the Apps Script backup. Run: npm run build:apps-script
// test/apps-script.test.ts fails if the committed Shared.js is out of date.
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const ENTRY = resolve(here, "../../apps-script/src/shared.ts");
export const OUT = resolve(here, "../../apps-script/Shared.js");

const HEADER = `// GENERATED by \`npm run build:apps-script\` in backend/worker from backend/apps-script/src/shared.ts.
// Do not edit: change the Worker's source and rebuild. Paste into the Apps Script file "Shared".
`;

export async function bundleShared() {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    write: false,
    format: "iife",
    globalName: "LiquidLyf",
    target: "es2017",       // Apps Script V8: keep the syntax conservative
    platform: "neutral",
    charset: "utf8",
    legalComments: "none",
    logLevel: "silent",
  });
  return HEADER + result.outputFiles[0].text;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, await bundleShared());
  console.log(`wrote ${OUT}`);
}
